# init.rb - 邀请码注册插件入口
#
# 无需 setup 钩子：插件模型 InvitationCode 类经 autoload 常驻，
# requirement_enabled? 内部检查插件开关，核心注册流程调用点零修改。
#
# 功能：
#   - 系统设置中可开启「邀请码注册」并自定义提示文案
#   - 开启后：邮箱/用户名注册、OAuth 新用户、API v1 注册均需有效邀请码
#   - 后台「邀请码管理」：批量生成、查看使用进度、删除
#   - 使用邀请码注册的用户会记录关联（users.invitation_code_id）
#
# 插件停用时：注册流程不再要求邀请码、后台入口与设置开关自动隐藏，
# 已生成的邀请码与关联数据保留。
